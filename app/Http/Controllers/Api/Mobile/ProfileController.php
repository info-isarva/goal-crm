<?php
namespace App\Http\Controllers\Api\Mobile;

use App\Http\Controllers\Controller;
use App\Models\Lead;
use App\Models\Deal;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Carbon\Carbon;

class ProfileController extends Controller
{
    public function show(Request $request)
    {
        $user = Auth::guard('sanctum')->user();
        if (!$user) {
            return response()->json([
                'success' => false,
                'message' => 'Invalid or missing token',
            ], 401);
        }

        $crmRoleType = $user->crm_role_type;
        $currentMonth = Carbon::now()->startOfMonth();
        $totalLeads = 0;
        $totalDealsWon = 0;
        $conversionPercentage = 0;
        $totalRevenue = 0;

        if (in_array($crmRoleType, [0, 1])) {
            // Count all leads for the current month
            $totalLeads = Lead::where('created_at', '>=', $currentMonth)->count();

            // Count all deals with stage "closed won" for the current month
            $totalDealsWon = Deal::where('stage_id', \App\Models\Stage::closedWonId())
                ->where('close_date', '>=', $currentMonth)
                ->count();

            // Calculate conversion percentage
            $conversionPercentage = $totalLeads > 0 ? ($totalDealsWon / $totalLeads) * 100 : 0;

            // Calculate total revenue from "closed won" deals for the current month
            $totalRevenue = Deal::where('stage_id', \App\Models\Stage::closedWonId())
                ->where('close_date', '>=', $currentMonth)
                ->sum('amount');
        } else {
            // Count leads generated by the user
            $totalLeads = Lead::where('created_by', $user->id)
                ->where('created_at', '>=', $currentMonth)
                ->count();

            // Count deals created by the user
            $totalDealsWon = Deal::where('created_by', $user->id)
                ->where('stage_id', \App\Models\Stage::closedWonId())
                ->where('close_date', '>=', $currentMonth)
                ->count();

            // Calculate conversion percentage for the user's leads
            $conversionPercentage = $totalLeads > 0 ? ($totalDealsWon / $totalLeads) * 100 : 0;

            // Calculate revenue generated by the user from "closed won" deals
            $totalRevenue = Deal::where('created_by', $user->id)
                ->where('stage_id', \App\Models\Stage::closedWonId())
                ->where('close_date', '>=', $currentMonth)
                ->sum('amount');
        }

        return response()->json([
            'success' => true,
            // 'user' => $user,
            'data' => [
                'total_leads' => $totalLeads,
                'deals_won' => $totalDealsWon,
                'conversion_percentage' => $conversionPercentage,
                'total_revenue' => $totalRevenue,
                'avatar' => $user->avatar ? url('/assets/employee_profile_image/'.$user->avatar) : null,
            ],
        ]);
    }

    //change password
    public function changePassword(Request $request)
    {
        $user = Auth::guard('sanctum')->user();
        if (!$user) {
            return response()->json([
                'success' => false,
                'message' => 'Invalid or missing token',
            ], 401);
        }
        $request->validate([
            'current_password' => 'required',
            'new_password' => 'required|min:6',
            'confirm_password' => 'required|same:new_password',
        ]);
        if (!password_verify($request->current_password, $user->password)) {
            return response()->json([
                'success' => false,
                'message' => 'Current password is incorrect',
            ], 400);
        }
        $user->password = bcrypt($request->new_password);
        $user->save();

        return response()->json([
            'success' => true,
            'message' => 'Password changed successfully',
        ]);
    }
}
